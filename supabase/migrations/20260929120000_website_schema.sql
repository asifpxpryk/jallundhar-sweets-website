create table if not exists public.menu_items (
  id text primary key,
  category_id text,
  name text not null,
  description text,
  price numeric not null,
  image_url text,
  is_available boolean default true,
  is_hidden boolean default false,
  sort_order integer default 0
);

alter table public.menu_items enable row level security;
drop policy if exists "public can read menu" on public.menu_items;
create policy "public can read menu" on public.menu_items
  for select to anon, authenticated using (true);
grant select on public.menu_items to anon, authenticated;

create table if not exists public.store_visibility (
  kind text not null check (kind in ('section', 'aisle')),
  slug text not null,
  hidden boolean not null default false,
  primary key (kind, slug)
);

alter table public.store_visibility enable row level security;
drop policy if exists "store_visibility_public_read" on public.store_visibility;
create policy "store_visibility_public_read" on public.store_visibility
  for select to anon, authenticated using (true);
grant select on public.store_visibility to anon, authenticated;

create table if not exists public.orders (
  id uuid primary key default gen_random_uuid(),
  order_number integer generated by default as identity,
  customer_name text,
  phone text not null,
  address text,
  location text,
  payment_method text,
  notes text,
  subtotal numeric,
  total numeric,
  created_at timestamptz default now()
);

create table if not exists public.order_items (
  id uuid primary key default gen_random_uuid(),
  order_id uuid references public.orders (id) on delete cascade,
  item_name text not null,
  quantity integer not null,
  unit_price numeric,
  line_total numeric
);

alter table public.orders enable row level security;
alter table public.order_items enable row level security;
drop policy if exists "public can insert orders" on public.orders;
create policy "public can insert orders" on public.orders
  for insert to anon, authenticated with check (true);
drop policy if exists "public can insert order items" on public.order_items;
create policy "public can insert order items" on public.order_items
  for insert to anon, authenticated with check (true);
grant insert on public.orders, public.order_items to anon, authenticated;
grant usage, select on all sequences in schema public to anon, authenticated;

